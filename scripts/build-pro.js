// Builds the employer-safe site (no independent projects) into pro/ from the
// full site. Cloudflare Pages runs this as its build command; output: pro/.
//
//   node scripts/build-pro.js         build pro/ (and cv/pro.html)
//   node scripts/build-pro.js --cv    only write cv/pro.html (used by generate_cv.py)
//
// The root files are the only source; pro/ and cv/pro.html are generated.
// Anything about independent (personal) projects sits between markers and is
// dropped here, and an optional pro-only line can follow the block:
//
//   HTML  <!-- personal --> … <!-- /personal -->    <!-- pro: … -->
//   JS    // personal … // /personal                // pro: …
//
// Links to 7mahfuz.github.io (which shows everything) become PRO_URL, or are
// dropped while PRO_URL is empty. The build fails if any personal project name
// is left in the output.
const fs = require('fs');
const path = require('path');

// The Cloudflare site's address, e.g. 'https://mahfuzurrahman.dev/'. Can also
// be set as a PRO_URL environment variable in the Cloudflare build settings.
const PRO_URL = process.env.PRO_URL || '';

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'pro');
const PAGES = ['index.html', 'games.html'];
const CV_SRC = 'cv/full.html';
const CV_OUT = 'cv/pro.html';
const CV_PDF = 'cv/Net_CV_MahfuzurRahman.pro.pdf';
const FULL_URL = 'https://7mahfuz.github.io/';
const FULL_HOST = '7mahfuz.github.io';

// Anything here in the output means a personal block was not marked.
const LEAKS = ['mapcars', 'motorshut', 'motors hut', 'aykorgpt', 'vetmart', 'cumilla resort', 'cumilla-resort',
  'resortmahfuz', 'independent project', FULL_HOST, '<!-- personal', '// personal'];

const MARKERS = {
  html: { start: '<!-- personal -->', end: '<!-- /personal -->', pro: /^(\s*)<!-- pro: (.*) -->\s*$/ },
  js: { start: '// personal', end: '// /personal', pro: /^(\s*)\/\/ pro: (.*)$/ }
};

function strip(text, kind, file) {
  const m = MARKERS[kind];
  const out = [];
  let open = 0;
  text.split('\n').forEach((line, i) => {
    const t = line.trim();
    if (t === m.start) {
      if (open) throw new Error(`${file}:${i + 1}: nested personal block`);
      open = i + 1;
    } else if (t === m.end) {
      if (!open) throw new Error(`${file}:${i + 1}: personal end without start`);
      open = 0;
    } else if (!open) {
      const p = line.match(m.pro);
      out.push(p ? p[1] + p[2] : line);
    }
  });
  if (open) throw new Error(`${file}:${open}: personal block never closed`);
  return out.join('\n');
}

function urls(text) {
  if (!PRO_URL) return text.split('\n').filter(l => !l.includes(FULL_HOST)).join('\n');
  const host = PRO_URL.replace(/^https?:\/\//, '').replace(/\/$/, '');
  return text.split(FULL_URL).join(PRO_URL).split(FULL_HOST).join(host);
}

function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), 'utf8');
}

function write(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

function checkLeaks(file, text) {
  const lower = text.toLowerCase();
  const found = LEAKS.filter(w => lower.includes(w.toLowerCase()));
  if (found.length) throw new Error(`${path.relative(ROOT, file)} still mentions: ${found.join(', ')}`);
}

function buildCv() {
  const html = urls(strip(read(CV_SRC), 'html', CV_SRC))
    .replace('<html', `<!-- Generated by scripts/build-pro.js from ${CV_SRC}. Do not edit. -->\n<html`);
  const file = path.join(ROOT, CV_OUT);
  checkLeaks(file, html);
  write(file, html);
  console.log(`[ok] ${CV_OUT}`);
}

// Local files a page or stylesheet points at.
function localRefs(text) {
  const refs = [...text.matchAll(/(?:href|src)="([^"]+)"|url\(["']?([^"')]+)["']?\)/g)].map(m => m[1] || m[2]);
  // %23 is an escaped "#": a fragment inside an inline SVG data URI.
  return refs.filter(r => !/^(https?:|\/\/|#|%23|mailto:|tel:|data:)/.test(r)).map(r => r.split(/[?#]/)[0]);
}

function buildSite() {
  fs.rmSync(OUT, { recursive: true, force: true });
  const queue = [];
  const done = new Set();

  PAGES.forEach(page => {
    const html = urls(strip(read(page), 'html', page));
    write(path.join(OUT, page), html);
    done.add(page);
    localRefs(html).forEach(r => queue.push(r));
  });

  while (queue.length) {
    const rel = queue.shift();
    if (done.has(rel)) continue;
    done.add(rel);
    const dest = path.join(OUT, rel);

    if (rel === 'Net_CV_MahfuzurRahman.pdf') {
      if (!fs.existsSync(path.join(ROOT, CV_PDF))) throw new Error(`${CV_PDF} is missing; run python scripts/generate_cv.py`);
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.copyFileSync(path.join(ROOT, CV_PDF), dest);
    } else if (rel.endsWith('.js')) {
      write(dest, urls(strip(read(rel), 'js', rel)));
    } else if (rel.endsWith('.css')) {
      const css = read(rel);
      write(dest, css);
      localRefs(css).forEach(r => queue.push(path.posix.join(path.posix.dirname(rel), r)));
    } else {
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.copyFileSync(path.join(ROOT, rel), dest);
    }
  }

  // Every text file that will be served gets the leak check.
  [...done].filter(r => /\.(html|js|css)$/.test(r)).forEach(r => {
    const file = path.join(OUT, r);
    checkLeaks(file, fs.readFileSync(file, 'utf8'));
  });
  console.log(`[ok] pro/ — ${done.size} files${PRO_URL ? `, links to ${PRO_URL}` : ', no site URL set (PRO_URL)'}`);
}

try {
  buildCv();
  if (!process.argv.includes('--cv')) buildSite();
} catch (e) {
  console.error(`[build-pro] ${e.message}`);
  process.exit(1);
}
